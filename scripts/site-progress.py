#!/usr/bin/env python3
"""Generate site/data/progress.json — the data behind the /status page.

Collects public evidence about the state of the project:

* GitHub public surface (open issues/PRs, latest green CI run on dev with
  test totals, latest release) via the REST API — the ``gh`` CLI when
  available (authenticated locally, token-authenticated in CI via GH_TOKEN),
  unauthenticated api.github.com as a fallback,
* a snapshot of the local beads board (ids/titles/statuses only, never
  comments or descriptions). bd and its .beads database are local-only, so
  the committed snapshot site/data/beads-snapshot.json is refreshed whenever
  a local run has bd available and carried forward (marked with its age)
  otherwise.

Design invariants (issue #515 §3.1, §6):

* Deterministic: identical inputs produce identical output.
* Fails loudly on missing sources under --strict instead of emitting stale
  data silently. Data that can only be carried forward is marked with its
  own regeneration timestamp — never presented as fresh.
* Allowlists public sources only: no secrets, no private issue bodies, no
  tracker comments. Beads contribute {id, title, status} exclusively.
* Generated files carry a "generated by scripts/site-progress.py" marker.

Usage:
    python3 scripts/site-progress.py [--repo-root DIR] [--output DIR] [--strict]

Exit codes: 0 success, 1 fatal (missing/failing source under --strict).
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import shutil
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path

GENERATED_BY = "scripts/site-progress.py"
GENERATED_NOTE = f"generated by {GENERATED_BY} — do not hand-edit"

GITHUB_API = "https://api.github.com"

# Tracker statuses considered finished; finished items stay off /status.
BEADS_DONE_STATUSES = {"closed", "done"}

# Gauntlet job whose libtest lines are summed for the test totals.
CI_TEST_JOB = "ubuntu-latest / stable"
# The workflows API accepts the workflow's bare file name (not its path).
CI_WORKFLOW_FILE = "ci.yml"
CI_BRANCH = "dev"

# How many recent open issues/PRs become individual entries.
ENTRY_LIMIT = 20

BEADS_ROW_KEYS = ("id", "title", "status")


class CollectorError(RuntimeError):
    """Fatal collection error; under --strict the run aborts with exit 1."""


def utc_now() -> str:
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat()


def run(cmd: list[str], cwd: Path | None = None) -> str:
    """Run a command and return stdout; raise CollectorError on failure."""
    try:
        proc = subprocess.run(
            cmd,
            cwd=str(cwd) if cwd else None,
            capture_output=True,
            text=True,
            timeout=120,
        )
    except FileNotFoundError as exc:
        raise CollectorError(f"required tool not found: {cmd[0]!r}") from exc
    except subprocess.TimeoutExpired as exc:
        raise CollectorError(f"command timed out: {' '.join(cmd)}") from exc
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout or "").strip()[:500]
        raise CollectorError(
            f"command failed ({proc.returncode}): {' '.join(cmd)}\n{detail}"
        )
    return proc.stdout


def git_repo_slug(repo_root: Path) -> str:
    """Return the 'owner/name' slug for the origin remote."""
    url = run(["git", "config", "--get", "remote.origin.url"], cwd=repo_root)
    match = re.search(r"[:/]([^/:]+/[^/]+?)(?:\.git)?$", url.strip())
    if not match:
        raise CollectorError(f"cannot parse owner/repo from remote: {url!r}")
    return match.group(1)


def gh_api(
    path: str,
    repo_root: Path | None = None,
    accept: str = "application/vnd.github+json",
) -> object:
    """GET a GitHub API path via the gh CLI, falling back to unauthenticated.

    CI checkouts have no stored gh credentials, so the workflow maps the job
    token into GH_TOKEN (gh picks it up automatically). The unauthenticated
    fallback keeps read-only collection working elsewhere, within the
    60 req/h shared limit.
    """
    gh_error: Exception | None = None
    if shutil.which("gh") is not None:
        try:
            raw = run(
                ["gh", "api", path, "-H", f"Accept: {accept}"],
                cwd=repo_root,
            )
            return json.loads(raw)
        except (CollectorError, json.JSONDecodeError) as exc:
            gh_error = exc  # fall through to the unauthenticated request
    url = (
        path
        if path.startswith("http")
        else f"{GITHUB_API}/{path.lstrip('/')}"
    )
    req = urllib.request.Request(url, headers={"Accept": accept})
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except (urllib.error.URLError, json.JSONDecodeError, OSError) as exc:
        detail = f" (gh attempt failed first: {gh_error})" if gh_error else ""
        raise CollectorError(
            f"GitHub API request failed: {url}{detail}"
        ) from exc


# ---------------------------------------------------------------------------
# Beads board


def load_beads_snapshot(repo_root: Path) -> dict | None:
    path = repo_root / "site" / "data" / "beads-snapshot.json"
    if not path.is_file():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise CollectorError(f"invalid beads snapshot {path}: {exc}") from exc


def write_beads_snapshot(repo_root: Path, items: list[dict]) -> dict:
    snapshot = {
        "_note": f"{GENERATED_NOTE} (local bd refresh)",
        "regenerated_at": utc_now(),
        "items": [
            {key: item.get(key) for key in BEADS_ROW_KEYS}
            for item in sorted(
                items, key=lambda i: (str(i.get("id", "")), str(i.get("title", "")))
            )
        ],
    }
    path = repo_root / "site" / "data" / "beads-snapshot.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(snapshot, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    return snapshot


def collect_beads(repo_root: Path) -> tuple[list[dict], dict]:
    """Return (items, source_meta) for the beads board.

    items is the raw allowlisted rows [{id, title, status}] for ALL beads;
    callers filter finished ones out for display. source_meta records whether
    the data is fresh (bd ran now) or a carried-forward snapshot, with its
    own regeneration timestamp so it is never presented as current.
    """
    if shutil.which("bd") is not None:
        try:
            raw = run(["bd", "list", "--json"], cwd=repo_root)
            parsed = json.loads(raw)
            rows = [
                {key: item.get(key) for key in BEADS_ROW_KEYS}
                for item in parsed
                if item.get("id") and item.get("title")
            ]
            snapshot = write_beads_snapshot(repo_root, parsed)
            return rows, {
                "fresh": True,
                "regenerated_at": snapshot["regenerated_at"],
                "note": "refreshed from bd in this run",
                "item_count": len(rows),
            }
        except (CollectorError, json.JSONDecodeError, KeyError) as exc:
            # bd present but unusable here (e.g. no .beads database in this
            # checkout — forks and CI). Degrade to the committed snapshot,
            # marked stale; only a missing snapshot is fatal below. The note
            # stays a fixed string: command diagnostics (paths, config
            # details) must not leak into generated public metadata.
            print(f"warning: bd list failed: {exc}", file=sys.stderr)
            snapshot = load_beads_snapshot(repo_root)
            if snapshot is None:
                raise CollectorError("bd list failed in this checkout") from exc
            return snapshot.get("items", []), {
                "fresh": False,
                "regenerated_at": snapshot.get("regenerated_at"),
                "note": (
                    "bd unavailable in this checkout; "
                    "carried-forward committed snapshot"
                ),
                "item_count": len(snapshot.get("items", [])),
            }
    snapshot = load_beads_snapshot(repo_root)
    if snapshot is None:
        raise CollectorError(
            "bd unavailable and no committed beads snapshot at "
            "site/data/beads-snapshot.json — run locally with bd installed "
            "to refresh the snapshot"
        )
    return snapshot.get("items", []), {
        "fresh": False,
        "regenerated_at": snapshot.get("regenerated_at"),
        "note": (
            "bd not available here; carried-forward snapshot from the "
            "committed file (refreshed by a local run)"
        ),
        "item_count": len(snapshot.get("items", [])),
    }


